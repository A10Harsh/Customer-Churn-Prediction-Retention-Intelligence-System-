"""Generate or verify DVC dependency closures from the resolved environment lock."""

import argparse
import platform
from collections import deque
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "requirements-lock.txt"
GROUPS = {
    "data": (
        "numpy",
        "pandas",
        "pandera[pandas]",
        "pyarrow",
        "pyyaml",
        "scikit-learn",
        "scipy",
    ),
    "analysis": (
        "numpy",
        "pandas",
        "scipy",
        "scikit-learn",
        "matplotlib",
        "seaborn",
        "statsmodels",
        "pyyaml",
    ),
    "training": (
        "numpy",
        "pandas",
        "scikit-learn",
        "scipy",
        "xgboost",
        "shap",
        "mlflow",
        "imbalanced-learn",
        "matplotlib",
        "pyyaml",
        "joblib",
        "optuna",
        "torch",
        "pandera[pandas]",
        "pyarrow",
    ),
}


def lock_pins():
    pins = {}
    for line in LOCK.read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        name, version = line.split("==", 1)
        key = canonicalize_name(name)
        if key in pins:
            raise ValueError(f"Duplicate lock pin: {name}")
        pins[key] = version
    return pins


def closure(roots, pins):
    queue = deque()
    for raw in roots:
        req = Requirement(raw)
        queue.append((canonicalize_name(req.name), ""))
        queue.extend((canonicalize_name(req.name), extra) for extra in req.extras)
    seen = set()
    names = set()
    environment = default_environment()
    while queue:
        name, extra = queue.popleft()
        if (name, extra) in seen:
            continue
        seen.add((name, extra))
        if name not in pins:
            raise ValueError(f"Dependency {name} has no resolved lock pin")
        distribution = metadata.distribution(name)
        if distribution.version != pins[name]:
            raise ValueError(
                f"Installed {name}=={distribution.version} "
                f"differs from lock {pins[name]}"
            )
        names.add(name)
        for raw in distribution.requires or ():
            req = Requirement(raw)
            if req.marker and not req.marker.evaluate({**environment, "extra": extra}):
                continue
            child = canonicalize_name(req.name)
            queue.append((child, ""))
            queue.extend((child, selected) for selected in req.extras)
    return names


def content(group, roots, pins):
    names = closure(roots, pins)
    lines = [
        f"# DVC {group} dependency closure from requirements-lock.txt",
        "# generated by scripts/check_deps_consistency.py --write",
        f"# roots: {', '.join(roots)}",
        f"# python: {platform.python_version()}",
        f"# platform: {platform.system().lower()}-{platform.machine().lower()}",
    ]
    lines.extend(f"{name}=={pins[name]}" for name in sorted(names))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    pins = lock_pins()
    for group, roots in GROUPS.items():
        path = ROOT / "dvc" / f"deps-{group}.txt"
        expected = content(group, roots, pins)
        if args.write:
            path.write_text(expected)
        elif not path.exists() or path.read_text() != expected:
            raise SystemExit(f"Stale DVC dependency manifest: {path}")
        print(f"{group}: {len(closure(roots, pins))} pinned packages")
    print("DVC dependency manifests consistent with lock and installed metadata")


if __name__ == "__main__":
    main()
